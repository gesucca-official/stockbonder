import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {parseEuroData,semicolonCSV} from '../lib/euro-source.ts';
import {rankBonds,DEFAULT_PREFERENCES as defaults,priceShock,EURO_COUNTRIES} from '../lib/euro-bonds.ts';
const fixture=name=>gunzipSync(readFileSync(new URL('../tests/fixtures/'+name,import.meta.url))).toString();
const csv=fixture('euro-eod-2026-10-20.csv.gz'),html=fixture('euro-monitor-2026-10-20.html.gz');
const data=parseEuroData(csv,html,new Date('2026-10-21T12:00:00Z'));
assert.equal(data.asOf,'2026-10-20');assert.ok(data.bonds.length>500);assert.equal(new Set(data.bonds.map(b=>b.country)).size,21);
const oat=data.bonds.find(b=>b.isin==='FR0000571218');
assert.equal(oat.price,103.76);assert.equal(oat.yield,3.89);assert.equal(oat.duration,2.27);assert.equal(oat.priceType,'LP');assert.equal(oat.coupon,5.5);
assert.equal(oat.date,'2026-10-20');assert.equal(oat.maturity,'2029-04-25');
assert.ok(data.bonds.every(b=>b.currency==='EUR'&&!/STEP|VALORE|FUTURA|indicizz/i.test(b.name)));
assert.ok(!data.bonds.some(b=>b.country==='IL'));
assert.throws(()=>parseEuroData('<html>Error</html>',html));
assert.throws(()=>parseEuroData(csv,'<html>Unavailable</html>'));
assert.deepEqual(semicolonCSV('a;b\n"semi;colon";"quoted""text"\n'),[{a:'semi;colon',b:'quoted"text'}]);
const make=(isin,y,d,rest={})=>({...oat,isin,country:'IT',yield:y,duration:d,volume:50000,lot:1000,maturity:'2035-01-01',...rest});
const bonds=[make('short',3,1),make('medium',4,4),make('long',4.4,7),make('dominated',3.5,5),make('stale',12,1,{date:'2026-09-01'}),make('reference',11,1,{priceType:'RP'}),make('untraded',10,1,{volume:0}),make('large',9,1,{lot:100000}),make('distant',8,15),make('soon',7,.1,{maturity:'2026-12-01'})];
const rank=p=>rankBonds(bonds,'IT',{...defaults,...p},'2026-10-21');
assert.equal(rank({}).best.isin,'long');
assert.equal(rank({penalty:20}).best.isin,'medium');
assert.equal(rank({penalty:50}).best.isin,'short');
assert.equal(rank({cap:3}).best.isin,'short');
assert.equal(rank({maxLot:500}).best,null);
assert.equal(rank({minVolume:100000}).best,null);
assert.equal(rank({}).rows.find(b=>b.isin==='dominated').efficient,false);
assert.equal(rank({}).eligible.length,4);
assert.equal(rankBonds(bonds,'IT',defaults,'2026-11-01').best,null);
assert.equal(rankBonds(bonds,'IT',defaults,'2026-10-19').best,null);
assert.equal(rankBonds([],'IT',defaults,'2026-10-21').best,null);
assert.equal(rankBonds([make('negative',-.5,1)],'IT',defaults,'2026-10-21').best.yield,-.5);
assert.equal(rankBonds([make('a',4,4),make('b',4,3)],'IT',{...defaults,penalty:0},'2026-10-21').best.isin,'b');
assert.equal(priceShock(5,100),-5);assert.equal(priceShock(5,-25),1.25);
for(const c of EURO_COUNTRIES){const r=rankBonds(data.bonds,c[0],defaults,'2026-10-21');assert.ok(!r.best||r.best.eligible&&r.best.efficient&&r.best.country===c[0]);}
console.log('PASS: real EUR export, source alignment, 21 countries, fixed-only classification, price dates, freshness, no-trade exclusions, lots, volume, maturity, duration, dominance, tie breaks, negative yields, empty selections and rate shocks.');
